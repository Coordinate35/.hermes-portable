# -*- coding: utf-8 -*-
"""
高标科技（广东高标智能科技）压力情景定量模型 v1
基准 = 2025年实际（招股说明书申报稿, 报告期2023-2025）
核心变量: m=材料涨幅, k=提价传导率(实际提价/所需提价), fx=汇率, q=量, ex=费用通胀

锚点公式:
  材料/收入  = M0/R0                 -> 每 m 材料通胀需要的价格对冲幅度
  ΔP_req(m)  = (M0/R0) * m           -> 维持毛利额所需提价
  ΔG(m,k)    = -(1-k) * m * M0       -> 毛利变动（售价=基准*(1+k*ΔP_req)）
  毛利平衡   m*  : G0 = (1-k)*m*M0
  净利平衡   m** : PBT0 = (1-k)*m*M0   (仅计毛利渠道)
"""
M0   = 127224.91 / 1e4   # 直接材料 12.7225亿
R0   = 205189.07 / 1e4   # 主营收入 20.5189亿
C0   = 154739.48 / 1e4   # 主营成本 15.4739亿
G0   = R0 - C0           # 主营毛利
PBT0 = 2.07589           # 利润总额 2.0759亿
NP0  = 1.81739           # 净利润 1.8174亿
TAX  = 1 - NP0 / PBT0    # 有效税率
E0   = 1.66801           # 境外收入 1.6680亿 (2025)
EXP0 = (5854.75 + 13468.29 + 8937.72 + 474.60) / 1e4   # 期间费用 2.8735亿

print(f"主营收入={R0:.2f} 主营成本={C0:.2f} 主营毛利={G0:.2f} 毛利率={G0/R0*100:.2f}%")
print(f"材料/收入={M0/R0:.4f}  毛利/材料={G0/M0:.4f}  有效税率={TAX*100:.2f}%  费用={EXP0:.2f}")

print("\n== 阈值：毛利盈亏平衡 m* 与 净利盈亏平衡 m** (材料涨幅) ==")
for k in [0, 0.3, 0.5, 0.65, 0.7, 0.8]:
    m_gross = G0 / ((1-k)*M0) * 100
    m_net   = PBT0 / ((1-k)*M0) * 100
    print(f"k={k:.2f}: m*={m_gross:6.1f}%   m**={m_net:6.1f}%")

print("\n== 单位换算：所需提价 (控制器均价45.23元/台) ==")
price = 45.23
for m in [0.25, 0.45, 0.70]:
    req = (M0/R0)*m
    dp  = price*req
    print(f"m={m:.0%}: 需提价 {req*100:5.1f}% = {dp:5.1f}元/台 = 整车(~2500元)的 {dp/2500*100:.2f}%")

print("\n== 毛利率矩阵 (行:m 列:k) ==")
for m in [0.25, 0.45, 0.70]:
    cells = []
    for k in [0, 0.5, 0.7, 1.0]:
        dG = -(1-k)*m*M0
        G2 = G0 + dG
        R2 = R0 * (1 + k*(M0/R0)*m)
        cells.append(f"k={k:.1f}: GM {G2/R2*100:5.1f}%")
    print(f"m={m:.0%} " + " | ".join(cells))

print("\n== 情景全桥 (亿元) ==")
def scen(name, m, k, fx, q, ex):
    dG   = -(1-k)*m*M0          # 成本-提价渠道
    dFx  = fx*E0                # 汇率折算(负值=升值损失)
    dVol = q*G0                 # 量(以毛利近似边际贡献)
    dExp = ex*EXP0              # 费用通胀
    dPBT = dG + dFx + dVol - dExp
    PBT2 = PBT0 + dPBT
    NP2  = PBT2*(1-TAX)
    R2   = R0*(1 + k*(M0/R0)*m)
    G2   = G0 + dG
    print(f"[{name}] m={m:.0%} k={k:.2f} fx={fx:.0%} q={q:.0%} ex=+{ex:.0%}")
    print(f"  收入 {R0:.2f}->{R2:.2f} | 毛利 {G0:.2f}->{G2:.2f} (GM {G0/R0*100:.1f}%->{G2/R2*100:.1f}%)")
    print(f"  拆解: 成本-提价 {dG:+.2f} | 汇率 {dFx:+.2f} | 量 {dVol:+.2f} | 费用 {-dExp:+.2f}")
    print(f"  利润总额 {PBT0:.2f}->{PBT2:.2f} | 净利润 {NP0:.2f}->{NP2:.2f} ({'亏损' if NP2<0 else f'{NP2/NP0*100-100:+.0f}%'})")
    return NP2

print()
s1 = scen("S1 温和",   0.25, 0.65, -0.05,  0.00, 0.10)
s2 = scen("S2 压力",   0.45, 0.50, -0.10, -0.05, 0.20)
# 2026-09-16 修订：S3 汇率假设 15% -> 30%（对美元约 1:5）
s3 = scen("S3 恶性",   0.70, 0.45, -0.30, -0.12, 0.30)

print("\n== k 修复敏感性(S2其它条件不变, k->0.8) ==")
scen("S2'", 0.45, 0.80, -0.10, -0.05, 0.20)

